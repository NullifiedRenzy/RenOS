type GeneratedSecrets struct {
	JWTSecret      string `json:"jwt_secret"`
	EncryptionKey  string `json:"encryption_key"`
	PostgresPass   string `json:"postgres_password"`
	RedisPassword  string `json:"redis_password"`
	NATSClusterKey string `json:"nats_cluster_key"`
}

func GenerateSecrets() (*GeneratedSecrets, error) {
	s := &GeneratedSecrets{}
	var err error
	s.JWTSecret, err = randomHex(32)
	if err != nil { return nil, err }
	s.EncryptionKey, err = randomHex(32)
	if err != nil { return nil, err }
	s.PostgresPass, err = randomAlphanum(32)
	if err != nil { return nil, err }
	s.RedisPassword, err = randomAlphanum(32)
	if err != nil { return nil, err }
	s.NATSClusterKey, err = randomHex(32)
	if err != nil { return nil, err }
	return s, nil
}

func randomHex(n int) (string, error) {
	b := make([]byte, n)
	if _, err := rand.Read(b); err != nil { return "", err }
	return hex.EncodeToString(b), nil
}

func randomAlphanum(n int) (string, error) {
	const charset = "abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789"
	b := make([]byte, n)
	if _, err := rand.Read(b); err != nil { return "", err }
	for i := range b { b[i] = charset[int(b[i])%len(charset)] }
	return string(b), nil
}

func GenerateTLSCert(installDir, hostname string) error {
	certDir := filepath.Join(installDir, "certs")
	if err := os.MkdirAll(certDir, 0700); err != nil { return err }

	key, err := rsa.GenerateKey(rand.Reader, 2048)
	if err != nil { return err }

	serial, _ := rand.Int(rand.Reader, new(big.Int).Lsh(big.NewInt(1), 128))
	template := &x509.Certificate{
		SerialNumber: serial,
		Subject: pkix.Name{
			Organization: []string{"RenOS"},
			CommonName:   hostname,
		},
		NotBefore:             time.Now(),
		NotAfter:              time.Now().Add(365 * 24 * time.Hour),
		KeyUsage:              x509.KeyUsageKeyEncipherment | x509.KeyUsageDigitalSignature,
		ExtKeyUsage:           []x509.ExtKeyUsage{x509.ExtKeyUsageServerAuth},
		BasicConstraintsValid: true,
		DNSNames:              []string{hostname, "localhost"},
		IPAddresses:           []net.IP{net.ParseIP("127.0.0.1"), net.ParseIP("::1")},
	}

	certDER, err := x509.CreateCertificate(rand.Reader, template, template, &key.PublicKey, key)
	if err != nil { return err }

	certFile := filepath.Join(certDir, "server.crt")
	keyFile := filepath.Join(certDir, "server.key")

	if err := os.WriteFile(certFile, pem.EncodeToMemory(&pem.Block{Type: "CERTIFICATE", Bytes: certDER}), 0644); err != nil { return err }
	keyDER := x509.MarshalPKCS1PrivateKey(key)
	if err := os.WriteFile(keyFile, pem.EncodeToMemory(&pem.Block{Type: "RSA PRIVATE KEY", Bytes: keyDER}), 0600); err != nil { return err }

	return nil
}

