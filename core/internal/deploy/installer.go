func CreateDirectories(installDir string) error {
	dirs := []string{
		filepath.Join(installDir, "certs"),
		filepath.Join(installDir, "data"),
		filepath.Join(installDir, "backups"),
		filepath.Join(installDir, "logs"),
		filepath.Join(installDir, "plugins"),
		filepath.Join(installDir, "deploy"),
	}
	for _, dir := range dirs {
		if err := os.MkdirAll(dir, 0755); err != nil { return err }
	}
	return nil
}

func InstallDependencies() error {
	// System dependencies that RenOS needs
	deps := []string{"curl", "wget", "unzip", "openssl"}
	for _, dep := range deps {
		if _, err := runCmd(nil, "which", dep); err != nil {
			// Try to install
			cmds := [][]string{
				{"apt-get", "install", "-y", dep},
				{"yum", "install", "-y", dep},
				{"dnf", "install", "-y", dep},
				{"pacman", "-S", "--noconfirm", dep},
				{"zypper", "install", "-y", dep},
			}
			for _, cmd := range cmds {
				c := exec.Command(cmd[0], cmd[1:]...)
				c.Stdout = nil
				c.Stderr = nil
				if c.Run() == nil { break }
			}
		}
	}
	return nil
}

func DockerComposeUp(installDir string) error {
	composeFile := filepath.Join(installDir, "deploy", "docker-compose.prod.yml")
	envFile := filepath.Join(installDir, ".env")

	cmd := exec.Command("docker", "compose", "-f", composeFile, "--env-file", envFile, "up", "-d", "--build")
	cmd.Dir = installDir
	cmd.Stdout = os.Stdout
	cmd.Stderr = os.Stderr
	return cmd.Run()
}

func WaitForHealthy(installDir string, timeout time.Duration) error {
	deadline := time.Now().Add(timeout)
	for time.Now().Before(deadline) {
		cmd := exec.Command("docker", "compose", "-f",
			filepath.Join(installDir, "deploy", "docker-compose.prod.yml"),
			"ps", "core")
		out, err := cmd.CombinedOutput()
		if err == nil && contains(string(out), "healthy") {
			return nil
		}
		time.Sleep(2 * time.Second)
	}
	return fmt.Errorf("services did not become healthy within %s", timeout)
}

func contains(s, sub string) bool {
	return len(s) >= len(sub) && (s == sub || len(s) > 0 && containsSubstr(s, sub))
}

func containsSubstr(s, sub string) bool {
	for i := 0; i <= len(s)-len(sub); i++ {
		if s[i:i+len(sub)] == sub { return true }
	}
	return false
}

func Rollback(installDir string) {
	composeFile := filepath.Join(installDir, "deploy", "docker-compose.prod.yml")
	envFile := filepath.Join(installDir, ".env")
	cmd := exec.Command("docker", "compose", "-f", composeFile, "--env-file", envFile, "down", "-v")
	cmd.Dir = installDir
	cmd.Run()
	os.RemoveAll(installDir)
}

type InstallationStatus struct {
	Phase       string        `json:"phase"`
	Progress    int           `json:"progress"`
	Message     string        `json:"message"`
	Error       string        `json:"error,omitempty"`
	Checks      []CheckResult `json:"checks,omitempty"`
	StartedAt   time.Time     `json:"started_at"`
	CompletedAt *time.Time    `json:"completed_at,omitempty"`
}

type Installer struct {
	Options    *ConfigOptions
	Secrets    *GeneratedSecrets
	Status     *InstallationStatus
	NonInteractive bool
	Result     chan InstallationStatus
}

func NewInstaller(opts *ConfigOptions, nonInteractive bool) *Installer {
	return &Installer{
		Options:        opts,
		NonInteractive: nonInteractive,
		Status:         &InstallationStatus{Phase: "init", StartedAt: time.Now()},
		Result:         make(chan InstallationStatus, 1),
	}
}

func (i *Installer) Run(ctx context.Context) error {
	steps := []struct {
		phase string
		fn    func(context.Context) error
	}{
		{"preflight", i.runPreflight},
		{"directories", i.createDirs},
		{"dependencies", i.installDeps},
		{"secrets", i.generateSecrets},
		{"tls", i.generateTLS},
		{"config", i.generateConfig},
		{"docker", i.startServices},
		{"health", i.waitForHealth},
		{"admin", i.createAdmin},
		{"verify", i.verifyInstallation},
	}

	total := len(steps)
	for idx, step := range steps {
		i.Status.Phase = step.phase
		i.Status.Progress = int(float64(idx) / float64(total) * 100)
		i.Status.Message = step.phase
		i.Result <- *i.Status

		if err := step.fn(ctx); err != nil {
			i.Status.Error = err.Error()
			i.Status.Phase = "failed"
			i.Result <- *i.Status
			Rollback(i.Options.InstallDir)
			return fmt.Errorf("installation failed at phase %s: %w", step.phase, err)
		}
	}

	now := time.Now()
	i.Status.Phase = "complete"
	i.Status.Progress = 100
	i.Status.Message = "Installation complete"
	i.Status.CompletedAt = &now
	i.Result <- *i.Status
	return nil
}

func (i *Installer) runPreflight(ctx context.Context) error {
	report, err := RunPreflightChecks(ctx)
	if err != nil { return err }
	i.Status.Checks = report.Results
	if !report.AllPassed {
		return fmt.Errorf("preflight checks failed: %d failures", report.FailCount)
	}
	return nil
}

func (i *Installer) createDirs(ctx context.Context) error {
	return CreateDirectories(i.Options.InstallDir)
}

func (i *Installer) installDeps(ctx context.Context) error {
	return InstallDependencies()
}

func (i *Installer) generateSecrets(ctx context.Context) error {
	s, err := GenerateSecrets()
	if err != nil { return err }
	i.Secrets = s
	return nil
}

func (i *Installer) generateTLS(ctx context.Context) error {
	if !i.Options.TLSEnabled { return nil }
	hostname := i.Options.Hostname
	if hostname == "" { hostname = "localhost" }
	return GenerateTLSCert(i.Options.InstallDir, hostname)
}

func (i *Installer) generateConfig(ctx context.Context) error {
	if err := GenerateEnvFile(i.Options.InstallDir, i.Options, i.Secrets); err != nil { return err }
	return GenerateDockerCompose(i.Options.InstallDir, i.Options)
}

func (i *Installer) startServices(ctx context.Context) error {
	return DockerComposeUp(i.Options.InstallDir)
}

func (i *Installer) waitForHealth(ctx context.Context) error {
	return WaitForHealthy(i.Options.InstallDir, 120*time.Second)
}

func (i *Installer) createAdmin(ctx context.Context) error {
	// Admin is created via the core service on startup (seedAdmin in main.go)
	return nil
}

func (i *Installer) verifyInstallation(ctx context.Context) error {
	// Verify all services are running
	cmd := exec.Command("docker", "compose", "-f",
		filepath.Join(i.Options.InstallDir, "deploy", "docker-compose.prod.yml"),
		"ps", "--format", "{{.Name}}: {{.Status}}")
	cmd.Dir = i.Options.InstallDir
	out, err := cmd.CombinedOutput()
	if err != nil { return fmt.Errorf("could not verify services: %w", err) }
	i.Status.Message = string(out)
	return nil
}
