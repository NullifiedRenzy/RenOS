func GenerateEnvFile(installDir string, opts *ConfigOptions, secrets *GeneratedSecrets) error {
	envPath := filepath.Join(installDir, ".env")

	data := envTemplateData{ConfigOptions: opts, GeneratedSecrets: secrets}

	tmpl, err := template.New("env").Parse(envTemplate)
	if err != nil { return err }

	f, err := os.Create(envPath)
	if err != nil { return err }
	defer f.Close()

	return tmpl.Execute(f, data)
}

