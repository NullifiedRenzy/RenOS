package main

import (
	"encoding/json"
	"fmt"
	"os"
	"path/filepath"
	"strconv"
	"strings"
)

type InstallConfig struct {
	Hostname           string   `json:"hostname"`
	TLSMode            string   `json:"tls_mode"`
	TLSCertPath        string   `json:"tls_cert_path,omitempty"`
	TLSKeyPath         string   `json:"tls_key_path,omitempty"`
	AdminEmail         string   `json:"admin_email"`
	AdminPassword      string   `json:"admin_password"`
	AdminName          string   `json:"admin_name"`
	DataDir            string   `json:"data_dir"`
	BackupDir          string   `json:"backup_dir"`
	BackupRetention    int      `json:"backup_retention"`
	AIProvider         string   `json:"ai_provider"`
	AIModel            string   `json:"ai_model"`
	MarketplaceEnabled bool     `json:"marketplace_enabled"`
	MarketplaceType    string   `json:"marketplace_type,omitempty"`
	Plugins            []string `json:"plugins"`
	ClusterMode        string   `json:"cluster_mode"`
	ClusterNodeCount   int      `json:"cluster_node_count"`
	InstallMethod      string   `json:"install_method"`
}

func (c *InstallConfig) Validate() []string {
	var errs []string

	if c.Hostname == "" {
		errs = append(errs, "hostname is required")
	} else if err := ValidateHostname(c.Hostname); err != nil {
		errs = append(errs, fmt.Sprintf("hostname: %v", err))
	}

	validTLS := map[string]bool{"none": true, "self-signed": true, "letsencrypt": true, "custom": true}
	if !validTLS[c.TLSMode] {
		errs = append(errs, "tls_mode must be one of: none, self-signed, letsencrypt, custom")
	}

	if c.TLSMode == "custom" {
		if c.TLSCertPath == "" {
			errs = append(errs, "tls_cert_path is required when TLS mode is custom")
		}
		if c.TLSKeyPath == "" {
			errs = append(errs, "tls_key_path is required when TLS mode is custom")
		}
	}

	if c.AdminEmail == "" {
		errs = append(errs, "admin_email is required")
	} else if err := ValidateEmail(c.AdminEmail); err != nil {
		errs = append(errs, fmt.Sprintf("admin_email: %v", err))
	}

	if c.AdminPassword == "" {
		errs = append(errs, "admin_password is required")
	} else if err := ValidatePassword(c.AdminPassword); err != nil {
		errs = append(errs, fmt.Sprintf("admin_password: %v", err))
	}

	if c.AdminName == "" {
		errs = append(errs, "admin_name is required")
	}

	if c.DataDir == "" {
		errs = append(errs, "data_dir is required")
	}
	if c.BackupDir == "" {
		errs = append(errs, "backup_dir is required")
	}
	if c.BackupRetention <= 0 {
		errs = append(errs, "backup_retention must be positive")
	}

	validAI := map[string]bool{"openai": true, "anthropic": true, "ollama": true, "none": true}
	if !validAI[c.AIProvider] {
		errs = append(errs, "ai_provider must be one of: openai, anthropic, ollama, none")
	}

	if c.AIProvider != "none" && c.AIModel == "" {
		errs = append(errs, "ai_model is required when ai_provider is set")
	}

	validModes := map[string]bool{"single": true, "cluster": true}
	if !validModes[c.ClusterMode] {
		errs = append(errs, "cluster_mode must be one of: single, cluster")
	}
	if c.ClusterMode == "cluster" && c.ClusterNodeCount < 2 {
		errs = append(errs, "cluster_node_count must be at least 2 for cluster mode")
	}

	validMethods := map[string]bool{"docker": true, "kubernetes": true, "bare-metal": true}
	if !validMethods[c.InstallMethod] {
		errs = append(errs, "install_method must be one of: docker, kubernetes, bare-metal")
	}

	return errs
}

func (c *InstallConfig) SaveToFile(path string) error {
	dir := filepath.Dir(path)
	if err := os.MkdirAll(dir, 0755); err != nil {
		return fmt.Errorf("creating directory: %w", err)
	}
	data, err := json.MarshalIndent(c, "", "  ")
	if err != nil {
		return fmt.Errorf("marshaling config: %w", err)
	}
	if err := os.WriteFile(path, data, 0644); err != nil {
		return fmt.Errorf("writing file: %w", err)
	}
	return nil
}

func LoadFromFile(path string) (*InstallConfig, error) {
	data, err := os.ReadFile(path)
	if err != nil {
		return nil, fmt.Errorf("reading file: %w", err)
	}
	var cfg InstallConfig
	if err := json.Unmarshal(data, &cfg); err != nil {
		return nil, fmt.Errorf("parsing config: %w", err)
	}
	return &cfg, nil
}

func (c *InstallConfig) GenerateEnvFile() string {
	var b strings.Builder
	b.WriteString("# RenOS Environment Configuration\n")
	b.WriteString("# Generated by RenOS Installer Wizard\n\n")

	writeEnv := func(key, value string) {
		if value != "" {
			fmt.Fprintf(&b, "%s=%s\n", key, value)
		}
	}

	writeEnv("RENOS_HOSTNAME", c.Hostname)
	writeEnv("RENOS_TLS_MODE", c.TLSMode)
	writeEnv("RENOS_TLS_CERT_PATH", c.TLSCertPath)
	writeEnv("RENOS_TLS_KEY_PATH", c.TLSKeyPath)
	writeEnv("RENOS_ADMIN_EMAIL", c.AdminEmail)
	writeEnv("RENOS_ADMIN_NAME", c.AdminName)
	writeEnv("RENOS_DATA_DIR", c.DataDir)
	writeEnv("RENOS_BACKUP_DIR", c.BackupDir)
	fmt.Fprintf(&b, "RENOS_BACKUP_RETENTION=%d\n", c.BackupRetention)
	writeEnv("RENOS_AI_PROVIDER", c.AIProvider)
	writeEnv("RENOS_AI_MODEL", c.AIModel)
	fmt.Fprintf(&b, "RENOS_MARKETPLACE_ENABLED=%v\n", c.MarketplaceEnabled)
	writeEnv("RENOS_MARKETPLACE_TYPE", c.MarketplaceType)
	writeEnv("RENOS_CLUSTER_MODE", c.ClusterMode)
	fmt.Fprintf(&b, "RENOS_CLUSTER_NODE_COUNT=%d\n", c.ClusterNodeCount)
	writeEnv("RENOS_INSTALL_METHOD", c.InstallMethod)

	return b.String()
}

