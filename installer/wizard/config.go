func (c *InstallConfig) SummaryRows() [][]string {
	plugins := "none"
	if len(c.Plugins) > 0 {
		plugins = strings.Join(c.Plugins, ", ")
	}

	marketplace := "disabled"
	if c.MarketplaceEnabled {
		marketplace = fmt.Sprintf("enabled (%s)", c.MarketplaceType)
	}

	clusterInfo := c.ClusterMode
	if c.ClusterMode == "cluster" {
		clusterInfo = fmt.Sprintf("cluster (%d nodes)", c.ClusterNodeCount)
	}

	tlsInfo := c.TLSMode
	if c.TLSMode == "custom" {
		tlsInfo = fmt.Sprintf("custom (cert: %s, key: %s)", c.TLSCertPath, c.TLSKeyPath)
	}

	aiInfo := c.AIProvider
	if c.AIProvider != "none" && c.AIModel != "" {
		aiInfo = fmt.Sprintf("%s (%s)", c.AIProvider, c.AIModel)
	}

	return [][]string{
		{"Hostname", c.Hostname},
		{"TLS Mode", tlsInfo},
		{"Admin", fmt.Sprintf("%s <%s>", c.AdminName, c.AdminEmail)},
		{"Data Directory", c.DataDir},
		{"Backup Directory", c.BackupDir},
		{"Backup Retention", fmt.Sprintf("%d days", c.BackupRetention)},
		{"AI Provider", aiInfo},
		{"Marketplace", marketplace},
		{"Plugins", plugins},
		{"Cluster", clusterInfo},
		{"Install Method", c.InstallMethod},
	}
}

func ValidateHostname(v string) error {
	if v == "" {
		return fmt.Errorf("hostname cannot be empty")
	}
	if len(v) > 253 {
		return fmt.Errorf("hostname too long (max 253 characters)")
	}
	host := strings.TrimRight(v, ".")
	if !strings.Contains(host, ".") {
		return fmt.Errorf("hostname must be a fully qualified domain name (e.g. renos.example.com)")
	}
	return nil
}

func ValidateEmail(v string) error {
	if v == "" {
		return fmt.Errorf("email cannot be empty")
	}
	parts := strings.SplitN(v, "@", 2)
	if len(parts) != 2 || parts[0] == "" || parts[1] == "" {
		return fmt.Errorf("invalid email address format")
	}
	if !strings.Contains(parts[1], ".") {
		return fmt.Errorf("email domain must contain a dot")
	}
	return nil
}

func ValidatePassword(v string) error {
	if len(v) < 8 {
		return fmt.Errorf("password must be at least 8 characters")
	}
	return nil
}

func ValidateDirectory(v string) error {
	if v == "" {
		return fmt.Errorf("directory path cannot be empty")
	}
	if !filepath.IsAbs(v) {
		return fmt.Errorf("directory path must be absolute")
	}
	return nil
}

func ValidateURL(v string) error {
	if v == "" {
		return fmt.Errorf("URL cannot be empty")
	}
	if !strings.HasPrefix(v, "http://") && !strings.HasPrefix(v, "https://") {
		return fmt.Errorf("URL must start with http:// or https://")
	}
	return nil
}

func ValidatePort(v string) error {
	port, err := strconv.Atoi(v)
	if err != nil {
		return fmt.Errorf("port must be a number")
	}
	if port < 1 || port > 65535 {
		return fmt.Errorf("port must be between 1 and 65535")
	}
	return nil
}

func ValidatePositiveInt(v string) error {
	n, err := strconv.Atoi(v)
	if err != nil {
		return fmt.Errorf("must be a number")
	}
	if n < 1 {
		return fmt.Errorf("must be a positive number")
	}
	return nil
}


