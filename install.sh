#!/usr/bin/env bash
set -euo pipefail

# RenOS One-Command Installer
# ============================
# Sets up a complete RenOS production environment.
#
# Usage:
#   curl -fsSL https://raw.githubusercontent.com/renos-project/renos/main/install.sh | bash
#   # Or locally:
#   ./install.sh
#
# What it does:
#   1. Checks prerequisites (Docker, Docker Compose)
#   2. Generates .env from .env.example with secure defaults
#   3. Generates secure JWT_SECRET and ENCRYPTION_KEY
#   4. Creates required directories
#   5. Pulls and starts all services
#   6. Waits for health checks
#   7. Creates initial admin user

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
ROOT_DIR="$SCRIPT_DIR"
ENV_FILE="$ROOT_DIR/.env"

# ─── Colors ──────────────────────────────────────────────────────────────────
RED='\033[0;31m'
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
BLUE='\033[0;34m'
NC='\033[0m'

info()  { echo -e "${BLUE}ℹ${NC}  $*"; }
ok()    { echo -e "${GREEN}✓${NC}  $*"; }
warn()  { echo -e "${YELLOW}⚠${NC}  $*"; }
fail()  { echo -e "${RED}✗${NC}  $*"; exit 1; }

echo ""
echo "╔══════════════════════════════════════════╗"
echo "║        RenOS Installer v0.1.0            ║"
echo "║    Your devices. One intelligent system. ║"
echo "╚══════════════════════════════════════════╝"
echo ""

# ─── 1. Check Prerequisites ──────────────────────────────────────────────────
info "Checking prerequisites..."

if ! command -v docker &>/dev/null; then
    fail "Docker is not installed. Install it from https://docs.docker.com/get-docker/"
fi
ok "Docker found: $(docker --version)"

if ! docker compose version &>/dev/null; then
    fail "Docker Compose V2 is not installed. Update Docker to the latest version."
fi
ok "Docker Compose found: $(docker compose version)"

if ! docker info &>/dev/null 2>&1; then
    fail "Docker daemon is not running. Start Docker and try again."
fi
ok "Docker daemon is running"

# ─── 2. Generate .env ────────────────────────────────────────────────────────
info "Configuring environment..."

if [ -f "$ENV_FILE" ]; then
    warn ".env already exists. Backing up to .env.backup"
    cp "$ENV_FILE" "$ENV_FILE.backup"
fi

# Generate secure random values
JWT_SECRET=$(openssl rand -hex 32 2>/dev/null || head -c 32 /dev/urandom | xxd -p | tr -d '\n')
ENCRYPTION_KEY=$(openssl rand -hex 32 2>/dev/null || head -c 32 /dev/urandom | xxd -p | tr -d '\n')
POSTGRES_PASSWORD=$(openssl rand -base64 24 2>/dev/null || head -c 24 /dev/urandom | base64 | tr -d '\n' | tr -d '/+=')

# Prompt for admin credentials
echo ""
echo -e "${BLUE}Admin User Setup${NC}"
read -p "  Admin email [admin@renos.local]: " ADMIN_EMAIL
ADMIN_EMAIL="${ADMIN_EMAIL:-admin@renos.local}"

read -s -p "  Admin password: " ADMIN_PASSWORD
echo ""

if [ -z "$ADMIN_PASSWORD" ]; then
    fail "Admin password cannot be empty."
fi

if [ ${#ADMIN_PASSWORD} -lt 8 ]; then
    fail "Admin password must be at least 8 characters."
fi

if [ "$ADMIN_PASSWORD" = "admin" ] || [ "$ADMIN_PASSWORD" = "password" ] || [ "$ADMIN_PASSWORD" = "changeme" ]; then
    fail "Admin password is too weak. Use a stronger password."
fi

# Prompt for external URL
echo ""
read -p "  External URL [https://localhost:8443]: " EXTERNAL_URL
EXTERNAL_URL="${EXTERNAL_URL:-https://localhost:8443}"

# Write .env file
cat > "$ENV_FILE" <<EOF
# RenOS Environment Configuration
# Generated by install.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ)

# ─── Database ────────────────────────────────────────────────────────────────
POSTGRES_USER=renos
POSTGRES_PASSWORD=${POSTGRES_PASSWORD}
POSTGRES_DB=renos

# ─── Core ────────────────────────────────────────────────────────────────────
RENOS_DATABASE_URL=postgres://renos:${POSTGRES_PASSWORD}@postgres:5432/renos?sslmode=disable
RENOS_NATS_URL=nats://nats:4222
RENOS_REDIS_URL=redis://redis:6379/0
RENOS_PORT=8443
RENOS_EXTERNAL_URL=${EXTERNAL_URL}
RENOS_LOG_LEVEL=info

# ─── Auth ────────────────────────────────────────────────────────────────────
RENOS_JWT_SECRET=${JWT_SECRET}
RENOS_ENCRYPTION_KEY=${ENCRYPTION_KEY}

# ─── CA ──────────────────────────────────────────────────────────────────────
RENOS_CA_CERT_DIR=/var/lib/renos/ca

# ─── Admin User ──────────────────────────────────────────────────────────────
RENOS_ADMIN_EMAIL=${ADMIN_EMAIL}
RENOS_ADMIN_PASSWORD=${ADMIN_PASSWORD}
EOF

ok "Environment configured (.env)"

# ─── 3. Create Directories ───────────────────────────────────────────────────
info "Creating directories..."

mkdir -p "$ROOT_DIR/deploy/nginx/ssl"
mkdir -p "$ROOT_DIR/backups"
mkdir -p "$ROOT_DIR/data/ca"

ok "Directories created"

# ─── 4. Build Docker Images ──────────────────────────────────────────────────
info "Building Docker images (this may take a few minutes)..."

cd "$ROOT_DIR"
docker compose -f docker-compose.prod.yml build

ok "Images built successfully"

# ─── 5. Start Services ───────────────────────────────────────────────────────
info "Starting services..."

docker compose -f docker-compose.prod.yml up -d

ok "Services started"

# ─── 6. Wait for Health ──────────────────────────────────────────────────────
info "Waiting for services to be healthy..."

MAX_WAIT=120
WAITED=0

while [ $WAITED -lt $MAX_WAIT ]; do
    if docker compose -f docker-compose.prod.yml ps core 2>/dev/null | grep -q "healthy"; then
        break
    fi
    sleep 2
    WAITED=$((WAITED + 2))
    echo -ne "\r    Waiting... ($WAITED/${MAX_WAIT}s)"
done
echo ""

if [ $WAITED -ge $MAX_WAIT ]; then
    warn "Services may still be starting. Check logs with:"
    warn "  docker compose -f docker-compose.prod.yml logs -f"
else
    ok "Core is healthy"
fi

# ─── 7. Summary ──────────────────────────────────────────────────────────────
echo ""
echo "╔══════════════════════════════════════════╗"
echo "║         Installation Complete!           ║"
echo "╚══════════════════════════════════════════╝"
echo ""
echo "  Dashboard:  http://localhost"
echo "  API:        http://localhost/api/v1/healthz"
echo "  Admin:      ${ADMIN_EMAIL}"
echo ""
echo "  Services:"
docker compose -f docker-compose.prod.yml ps --format "    {{.Name}}: {{.Status}}"
echo ""
echo "  Useful commands:"
echo "    docker compose -f docker-compose.prod.yml logs -f     # View logs"
echo "    docker compose -f docker-compose.prod.yml ps          # Service status"
echo "    docker compose -f docker-compose.prod.yml restart     # Restart all"
echo "    docker compose -f docker-compose.prod.yml down        # Stop all"
echo ""
echo "  Next steps:"
echo "    1. Open http://localhost and log in"
echo "    2. Change the default admin password"
echo "    3. Install RenAgent on your devices"
echo "    4. Configure TLS for production use"
echo ""
